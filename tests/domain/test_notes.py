"""Tests for laaw.notes (pure rendering + word caps)."""

import unittest

from laaw.domain import notes
from laaw.constants import NOTES_FILE_WORD_CAP, NOTE_WORD_CAP
from laaw.model.note import Note


def note(tag: str, words: int) -> Note:
    """A note whose text is exactly `words` whitespace-separated tokens."""
    return Note(tag=tag, text=" ".join(str(i) for i in range(words)))


def many_notes(tag: str, count: int, words_each: int) -> list[Note]:
    """`count` notes of `words_each` words each, all under the per-note cap."""
    assert words_each <= NOTE_WORD_CAP
    return [note(tag, words_each) for _ in range(count)]


class ValidateNoteTest(unittest.TestCase):
    def test_given_note_under_cap_when_validate_then_passes(self):
        # arrange
        n = note("decision", NOTE_WORD_CAP)
        # act / assert (no exception)
        notes.validate_note(n)

    def test_given_note_over_cap_when_validate_then_raises_value_error(self):
        # arrange
        n = note("decision", NOTE_WORD_CAP + 1)
        # act / assert
        with self.assertRaises(ValueError):
            notes.validate_note(n)


class RenderSmallTest(unittest.TestCase):
    def test_given_few_notes_when_render_then_only_notes_md(self):
        # arrange
        result = notes.render_notes([note("progress", 10), note("decision", 10)])
        # act / assert
        self.assertEqual(set(result), {"notes.md"})

    def test_given_two_small_tags_when_render_then_notes_md_has_blank_line_layout(self):
        # arrange: two tags, one note each
        result = notes.render_notes([note("progress", 3), note("decision", 2)])
        # act / assert: exact layout — blank after # Notes, after each ## header, between sections
        expected = (
            "<!-- generated by laaw; do not edit -->\n"
            "# Notes\n"
            "\n"
            "## progress\n"
            "\n"
            "- 0 1 2\n"
            "\n"
            "## decision\n"
            "\n"
            "- 0 1\n"
        )
        self.assertEqual(result["notes.md"], expected)

    def test_given_empty_notes_when_render_then_notes_md_with_header_only(self):
        # arrange
        result = notes.render_notes([])
        # act / assert
        self.assertIn("notes.md", result)
        self.assertTrue(result["notes.md"].startswith("<!-- generated by laaw"))


class RenderLargeTagTest(unittest.TestCase):
    def test_given_single_tag_over_cap_when_render_then_own_numbered_files(self):
        # arrange: one tag, many small notes totalling > 600 words
        big = many_notes("progress", 8, 100)  # 800 words total, each note 100
        result = notes.render_notes(big)
        # act / assert
        self.assertIn("notes.md", result)
        overflow = [f for f in result if f != "notes.md"]
        self.assertTrue(overflow)
        for fname in overflow:
            self.assertIn(fname, result["notes.md"])
            self.assertIn("progress", result["notes.md"])

    def test_given_overflow_file_when_render_then_exact_blank_line_layout(self):
        # arrange: one tag over the cap → its own overflow file(s)
        big = many_notes("progress", 7, 100)  # 700 words > 600
        result = notes.render_notes(big)
        overflow = [f for f in result if f != "notes.md"]
        self.assertTrue(overflow)
        bullet = "- " + " ".join(str(i) for i in range(100))
        total_bullets = 0
        for fname in overflow:
            text = result[fname]
            # exact layout: '## tag' + blank line + bullets, trailing newline
            self.assertTrue(text.startswith("## progress\n\n"))
            self.assertTrue(text.endswith(bullet + "\n"))
            body = [l for l in text.splitlines() if l.startswith("- ")]
            total_bullets += len(body)
            for line in body:
                self.assertEqual(line, bullet)
        self.assertEqual(total_bullets, 7)

    def test_given_large_tag_when_render_then_each_file_respects_cap(self):
        # arrange
        big = many_notes("gotcha", 8, 100)
        result = notes.render_notes(big)
        # act / assert: no overflow file's note content exceeds the cap
        for fname, text in result.items():
            if fname == "notes.md":
                continue
            # Count only note content (strip the leading '- ' bullet marker).
            body = [l[2:] for l in text.splitlines() if l.startswith("- ")]
            self.assertLessEqual(sum(len(l.split()) for l in body), NOTES_FILE_WORD_CAP)


class RenderMixedTest(unittest.TestCase):
    def test_given_mixed_small_tags_when_render_then_groups_into_shared_files(self):
        # arrange: three tags, each ~300 words (small notes), two fit per file
        result = notes.render_notes(
            many_notes("api", 3, 100)
            + many_notes("convention", 3, 80)
            + many_notes("module", 3, 80)
        )
        # act / assert
        self.assertIn("notes.md", result)
        for tag in ("api", "convention", "module"):
            self.assertTrue(any(tag in text for text in result.values()))

    def test_given_notes_when_render_then_every_overflow_linked_with_tags(self):
        # arrange: force overflow with several tags totalling well over the cap
        result = notes.render_notes(
            many_notes("api", 4, 100)
            + many_notes("convention", 4, 100)
            + many_notes("module", 4, 100)
        )
        # act / assert
        overflow = [f for f in result if f != "notes.md"]
        self.assertTrue(overflow)
        for fname in overflow:
            self.assertIn(fname, result["notes.md"])
            self.assertIn("(tags:", result["notes.md"])


if __name__ == "__main__":
    unittest.main()
